"""Sync product classes from the pinned pragmatic BIM data contract.

The contract identifies each product class (notation, short definition, hierarchy).
The Reference describes it in products/<code>.yaml (name, tender text, notes).

Usage:
    python scripts/sync_products.py --contract PATH          write generated files
    python scripts/sync_products.py --contract PATH --check  fail if they are stale
    python scripts/sync_products.py --contract PATH --seed   also create missing sheets
    python scripts/sync_products.py --values-only            rebuild value lists from
                                                             _names.yaml and the sheets

Generated, do not edit by hand:
    products/_names.yaml           name index of the pinned contract
    values/product-class-*.yaml    allowed-value lists for the product class attributes

PATH is a checkout of the contract at the commit in products/_contract-pin.yaml.
Reading the TTL files needs rdflib (pip install rdflib); --values-only does not.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
PRODUCTS_DIR = REPO_ROOT / "products"
VALUES_DIR = REPO_ROOT / "values"
PIN_PATH = PRODUCTS_DIR / "_contract-pin.yaml"
NAMES_PATH = PRODUCTS_DIR / "_names.yaml"
DOCS_BASE = "https://schema.pragmaticbim.ch/classification/"
LANGS = ("de", "fr", "it", "en")
NAMES_HEADER = (
    "# Generated by scripts/sync_products.py from the pinned data contract. Do not edit.\n"
    "# The contract identifies the product classes; products/<code>.yaml describes them.\n"
)


def sheet_path(code: str) -> Path:
    return PRODUCTS_DIR / f"{code.lower()}.yaml"


def sheet_id(code: str) -> str:
    return f"pragmaticbim:product/{code.lower()}"


def load_pin() -> dict[str, Any]:
    return yaml.safe_load(PIN_PATH.read_text(encoding="utf-8"))


def load_names() -> dict[str, Any]:
    return yaml.safe_load(NAMES_PATH.read_text(encoding="utf-8"))


def load_sheets() -> dict[str, dict[str, Any]]:
    sheets = {}
    for path in sorted(PRODUCTS_DIR.glob("*.yaml")):
        if path.name.startswith("_"):
            continue
        record = yaml.safe_load(path.read_text(encoding="utf-8"))
        sheets[record["product_classification"]["classification_code"]] = record
    return sheets


def dump(data: Any) -> str:
    return yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=10_000)


# --- contract side ----------------------------------------------------------------


def _literal(graph, subject, predicate, lang: str) -> str | None:
    for value in graph.objects(subject, predicate):
        if getattr(value, "language", None) == lang:
            return str(value)
    return None


def _file_order(text: str) -> dict[str, int]:
    """Concept notations in the order they appear in the TTL file."""
    order: dict[str, int] = {}
    for match in re.finditer(r'skos:notation\s+"([^"]+)"', text):
        order.setdefault(match.group(1), len(order))
    return order


def read_scheme(contract: Path, entry: dict[str, Any], slugs: dict[str, str]) -> tuple[dict, dict]:
    """Return (name-index scheme, tender texts by notation) for one TTL file."""
    from rdflib import RDF, Graph, Namespace

    skos = Namespace("http://www.w3.org/2004/02/skos/core#")
    dcterms = Namespace("http://purl.org/dc/terms/")
    path = contract / "classification" / entry["path"]
    text = path.read_text(encoding="utf-8")
    graph = Graph().parse(data=text, format="turtle")
    scheme = next(graph.subjects(RDF.type, skos.ConceptScheme))
    tops = set(graph.objects(scheme, skos.hasTopConcept))
    order = _file_order(text)

    concepts = []
    texts = {}
    for concept in graph.subjects(RDF.type, skos.Concept):
        notation = str(graph.value(concept, skos.notation))
        broader = graph.value(concept, skos.broader)
        record = {
            "code": notation,
            "iri": str(concept),
            "top": concept in tops,
            "broader": str(graph.value(broader, skos.notation)) if broader is not None else None,
            "label": {lang: _literal(graph, concept, skos.prefLabel, lang) for lang in ("de", "en")},
            "definition": {lang: _literal(graph, concept, skos.definition, lang) for lang in ("de", "en")},
            "ifc_class": str(graph.value(concept, dcterms.subject) or "") or None,
        }
        if record["broader"] is None:
            del record["broader"]
        if record["ifc_class"] is None:
            del record["ifc_class"]
        concepts.append(record)
        tender = {lang: _literal(graph, concept, dcterms.description, lang) for lang in ("de", "en")}
        if concept in tops and tender["de"]:
            texts[notation] = {lang: value for lang, value in tender.items() if value}
    concepts.sort(key=lambda item: order.get(item["code"], len(order)))

    result = {
        "scheme": str(graph.value(scheme, dcterms.identifier)),
        "path": entry["path"],
        "docs": f"{DOCS_BASE}{slugs[entry['path']]}.html" if entry["path"] in slugs else None,
        "title": {lang: _literal(graph, scheme, skos.prefLabel, lang) for lang in ("de", "en")},
        "value_set": entry.get("value_set"),
        "sheets": entry.get("sheets", True),
        "concepts": concepts,
    }
    if result["value_set"] is None:
        del result["value_set"]
    return result, texts


def contract_commit(contract: Path) -> str:
    return subprocess.run(
        ["git", "-C", str(contract), "rev-parse", "HEAD"], check=True, capture_output=True, text=True
    ).stdout.strip()


def build_names(contract: Path, pin: dict[str, Any]) -> tuple[dict, dict]:
    catalog = yaml.safe_load((contract / "classification" / "catalog.yaml").read_text(encoding="utf-8"))
    slugs = {item["path"]: item["slug"] for item in catalog.get("vocabularies", []) + catalog.get("mappings", [])}
    schemes, texts = [], {}
    for entry in pin["schemes"]:
        scheme, scheme_texts = read_scheme(contract, entry, slugs)
        schemes.append(scheme)
        texts.update(scheme_texts)
    return {"contract": {"repository": pin["repository"], "commit": pin["commit"]}, "schemes": schemes}, texts


# --- reference side ---------------------------------------------------------------


def value_set_code(scheme: dict[str, Any]) -> str:
    prefix = scheme["concepts"][0]["code"].split("-")[0]
    return f"PRODUCT-{prefix.upper()}"


def build_value_set(scheme: dict[str, Any], sheets: dict[str, dict]) -> dict[str, Any]:
    """Allowed-value list for one scheme: every concept, labels per language.

    German and English come from the contract. French and Italian come from the
    sheet name where one exists, otherwise they fall back to English.
    """
    docs = scheme["docs"]
    title_de, title_en = scheme["title"]["de"], scheme["title"]["en"]
    values: dict[str, list[str]] = {lang: [] for lang in LANGS}
    for concept in scheme["concepts"]:
        name = (sheets.get(concept["code"]) or {}).get("name") or {}
        for lang in LANGS:
            if lang in ("de", "en"):
                values[lang].append(concept["label"][lang])
            else:
                values[lang].append(name.get(lang) or concept["label"]["en"])
    return {
        "id": f"pragmaticbim:value/{scheme['value_set']}",
        "code": value_set_code(scheme),
        "name": {"de": title_de, "fr": title_en, "it": title_en, "en": title_en},
        "description": {
            "de": f"Produktklassen gemäss {title_de}. Quelle: {docs}",
            "fr": f"Classes de produits selon {title_en}. Source : {docs}",
            "it": f"Classi di prodotto secondo {title_en}. Fonte: {docs}",
            "en": f"Product classes according to {title_en}. Source: {docs}",
        },
        "year": 2026,
        "norm_reference": "Pragmatic BIM Data Contract (latest)",
        "status": "active",
        "values": values,
    }


def expected_value_sets(names: dict[str, Any], sheets: dict[str, dict]) -> dict[Path, str]:
    return {
        VALUES_DIR / f"{scheme['value_set']}.yaml": dump(build_value_set(scheme, sheets))
        for scheme in names["schemes"]
        if scheme.get("value_set")
    }


def seed_sheet(scheme: dict[str, Any], concept: dict[str, Any], sort_order: int, text: dict[str, str]) -> dict:
    return {
        "id": sheet_id(concept["code"]),
        "sort_order": sort_order,
        "status": "active",
        "name": {lang: concept["label"][lang] for lang in ("de", "en") if concept["label"][lang]},
        "product_classification": {
            "classification_scheme": scheme["scheme"],
            "classification_code": concept["code"],
        },
        "tender_text": text,
    }


def write_or_check(files: dict[Path, str], check: bool) -> list[Path]:
    stale = []
    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path)
            if not check:
                path.write_text(content, encoding="utf-8")
    return stale


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--contract", type=Path, help="checkout of the data contract at the pinned commit")
    parser.add_argument("--check", action="store_true", help="report stale files, write nothing")
    parser.add_argument("--seed", action="store_true", help="create missing sheets from the contract tender texts")
    parser.add_argument("--values-only", action="store_true", help="rebuild value lists from _names.yaml")
    args = parser.parse_args(argv)

    pin = load_pin()
    files: dict[Path, str] = {}
    if args.values_only:
        names = load_names()
    else:
        if args.contract is None:
            parser.error("--contract is required unless --values-only is given")
        commit = contract_commit(args.contract)
        if commit != pin["commit"]:
            print(f"contract checkout is at {commit}, pin is {pin['commit']}", file=sys.stderr)
            return 2
        names, texts = build_names(args.contract, pin)
        files[NAMES_PATH] = NAMES_HEADER + dump(names)
        if args.seed:
            sheets = load_sheets()
            for scheme in names["schemes"]:
                if not scheme["sheets"]:
                    continue
                tops = [concept for concept in scheme["concepts"] if concept["top"]]
                for order, concept in enumerate(tops, start=1):
                    path = sheet_path(concept["code"])
                    if concept["code"] in sheets or path.exists() or concept["code"] not in texts:
                        continue
                    files[path] = dump(seed_sheet(scheme, concept, order, texts[concept["code"]]))

    # Value lists read the sheets as they will be after this run.
    pending = {
        yaml.safe_load(content)["product_classification"]["classification_code"]: yaml.safe_load(content)
        for path, content in files.items()
        if path.parent == PRODUCTS_DIR and path != NAMES_PATH
    }
    files.update(expected_value_sets(names, {**load_sheets(), **pending}))

    stale = write_or_check(files, args.check)
    verb = "stale" if args.check else "wrote"
    for path in stale:
        print(f"{verb}: {path.relative_to(REPO_ROOT)}")
    print(f"{len(stale)} file(s) {verb}, {len(files) - len(stale)} up to date")
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
